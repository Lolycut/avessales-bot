SUBJECT_TRIGGER_WORDS = {
    "когда", "где", "отработка", "отработки", "отработке", "отработку", 
    "пары", "пара", "пару", "занятия", "занятие", "предмет", "предмету"
}


def extract_subject_from_query(text: str) -> tuple[str, str] | None:
    clean = re.sub(r"[^\w\s-]", " ", text.lower()).strip()
    words = clean.split()

    # 1. Поиск по словарю синонимов и сленга
    for canon_name, aliases in SUBJECT_ALIASES.items():
        for alias in aliases:
            for w in words:
                if len(w) >= 3 and (w.startswith(alias) or alias in w):
                    return canon_name, w

    # 2. Прямой поиск (если ввели редкий термин длиннее 4 букв)
    for w in words:
        if len(w) >= 4 and w not in SUBJECT_TRIGGER_WORDS:
            return w, w

    return None