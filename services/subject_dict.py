def extract_subject_from_query(text: str) -> tuple[str, list[str], str] | None:
    clean = re.sub(r"[^\w\s-]", " ", text.lower()).strip()
    clean = re.sub(r"\s+", " ", clean)

    # 1. Поиск точных многословных и составных алиасов
    for canon_name, data in SUBJECT_REGISTRY.items():
        for alias in data["user_aliases"]:
            pattern = rf"\b{re.escape(alias)}\b"
            if re.search(pattern, clean):
                return canon_name, data["schedule_stems"], alias

    # 2. Поиск по словам и основам
    words = [w for w in clean.split() if w not in STOP_WORDS_FOR_SUBJECTS and len(w) >= 3]
    for w in words:
        for canon_name, data in SUBJECT_REGISTRY.items():
            for alias in data["user_aliases"]:
                if len(alias) >= 3 and (w.startswith(alias) or alias.startswith(w)):
                    return canon_name, data["schedule_stems"], w

    # 3. Если прямо спросили "отработка по ..." или "пара по ..."
    fallback_match = re.search(r"(?:отработк[а-я]*|пар[а-я]* по|заняти[а-я]* по)\s+([а-яa-z]{3,})", clean)
    if fallback_match:
        raw_word = fallback_match.group(1)
        if raw_word not in STOP_WORDS_FOR_SUBJECTS:
            return raw_word.capitalize(), [raw_word[:4]], raw_word

    return None


SUBJECT_KEYS = list(SUBJECT_REGISTRY.keys())


def get_subject_id(canon_name: str) -> int:
    try:
        return SUBJECT_KEYS.index(canon_name)
    except ValueError:
        return -1


def get_subject_by_id(subj_id: int) -> str | None:
    if 0 <= subj_id < len(SUBJECT_KEYS):
        return SUBJECT_KEYS[subj_id]
    return None

