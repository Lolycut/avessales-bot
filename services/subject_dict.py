SUBJECT_INTENT_TRIGGERS = {
    "расписание", "пары", "пара", "пару", "когда", "где", "какая", "какой", "будет", 
    "скинь", "подскажи", "во сколько", "кабинет", "ауд", "аудитория", "препод", "отработка"
}


def extract_subject_from_query(text: str) -> tuple[str, str] | None:
    clean = re.sub(r"[^\w\s-]", " ", text.lower()).strip()
    words = clean.split()
    meaningful_words = [w for w in words if w not in STOP_WORDS_FOR_SUBJECTS]

    if not meaningful_words:
        return None

    # Если в сообщении много слов (>3), требуем явного контекста расписания/вопроса
    has_schedule_intent = any(t in clean for t in SUBJECT_INTENT_TRIGGERS)
    if len(words) > 3 and not has_schedule_intent:
        return None

    # 1. Проверка точных коротких аббревиатур (бжд, фк, ит, лат и т.д.)
    for canon_name, exact_set in EXACT_MATCH_ALIASES.items():
        for w in meaningful_words:
            if w in exact_set:
                return canon_name, w

    # 2. Поиск многословных словосочетаний
    for canon_name, aliases in SUBJECT_ALIASES.items():
        for alias in aliases:
            if " " in alias and alias in clean:
                return canon_name, alias

    # 3. Поиск по основам слов (w.startswith, длина от 4 символов)
    for canon_name, aliases in SUBJECT_ALIASES.items():
        for alias in aliases:
            if " " in alias:
                continue
            for w in meaningful_words:
                if len(w) >= 4 and len(alias) >= 4 and w.startswith(alias):
                    return canon_name, w

    if any(trigger in clean for trigger in ["отработк", "пары по", "пара по", "занятия по", "предмет"]):
        for w in meaningful_words:
            if len(w) >= 4:
                return w, w

    return None