def extract_subject_from_query(text: str) -> tuple[str, str] | None:
    clean = re.sub(r"[^\w\s-]", " ", text.lower()).strip()
    words = [w for w in clean.split() if w not in STOP_WORDS_FOR_SUBJECTS]

    if not words:
        return None

    # 1. Поиск по словарю синонимов и сленга
    for canon_name, aliases in SUBJECT_ALIASES.items():
        for alias in aliases:
            for w in words:
                if len(w) >= 3 and (w.startswith(alias) or alias in w):
                    return canon_name, w

    # 2. Прямой поиск (только при явном контексте: "отработка по...", "пары по...")
    has_explicit_trigger = any(
        trigger in clean for trigger in ["отработк", "пары по", "пара по", "занятия по", "предмет"]
    )
    if has_explicit_trigger:
        for w in words:
            if len(w) >= 4 and w not in STOP_WORDS_FOR_SUBJECTS:
                return w, w

    return None